using EKA.Application.Abstractions;
using EKA.Domain.Common;
using EKA.Infrastructure.Persistence;
using EKA.Infrastructure.Persistence.Interceptors;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging.Abstractions;
using Testcontainers.MsSql;

namespace EKA.IntegrationTests;

/// <summary>
/// A real SQL Server in a throwaway container, shared by every test in the collection.
/// </summary>
/// <remarks>
/// <para>
/// <b>Why a real database and not the in-memory provider.</b> Everything this step is
/// about — unique indexes, a filtered index, cascade deletes, column types, value
/// converters producing valid SQL — is precisely what the in-memory provider does not
/// implement. A test suite that passes against it would prove the C# compiles, not that
/// the schema works. The duplicate-chunk-index test below would pass in memory and fail in
/// production, which is the worst possible outcome.
/// </para>
/// <para>
/// One container per test run, not per test: starting SQL Server takes tens of seconds.
/// Tests isolate themselves with unique identifiers instead.
/// </para>
/// </remarks>
public sealed class SqlServerFixture : IAsyncLifetime
{
    /// <summary>
    /// Pinned to the same image the compose file uses, so developers and CI exercise the
    /// same engine version. An unpinned tag means a test that passes today can fail
    /// tomorrow for reasons unrelated to any commit.
    /// </summary>
    private const string SqlServerImage = "mcr.microsoft.com/mssql/server:2022-latest";

    // Testcontainers deprecated the parameterless builder precisely to stop implicit,
    // drifting image versions; passing the tag is now required rather than optional.
    private readonly MsSqlContainer _container = new MsSqlBuilder(SqlServerImage).Build();

    public string ConnectionString => _container.GetConnectionString();

    public async Task InitializeAsync()
    {
        await _container.StartAsync();

        // Apply migrations once for the shared database. Tests that specifically verify a
        // clean-database migration create their own database instead.
        await using var context = CreateContext();
        await context.Database.MigrateAsync();
    }

    public Task DisposeAsync() => _container.DisposeAsync().AsTask();

    /// <summary>
    /// Builds a context against the shared database, wired exactly as production is:
    /// the audit interceptor attached and a dispatcher in place.
    /// </summary>
    public EkaDbContext CreateContext(
        ICurrentUser? currentUser = null,
        IDomainEventDispatcher? dispatcher = null,
        string? connectionStringOverride = null)
    {
        var options = new DbContextOptionsBuilder<EkaDbContext>()
            .UseSqlServer(connectionStringOverride ?? ConnectionString)
            .AddInterceptors(new AuditInterceptor(currentUser ?? new TestCurrentUser(null)))
            .Options;

        return new EkaDbContext(
            options,
            dispatcher ?? new LoggingDomainEventDispatcher(
                NullLogger<LoggingDomainEventDispatcher>.Instance));
    }

    /// <summary>
    /// Creates an empty database on the same server and returns its connection string, so
    /// a test can prove a migration applies from nothing.
    /// </summary>
    public async Task<string> CreateEmptyDatabaseAsync(string databaseName)
    {
        await using (var connection = new SqlConnection(ConnectionString))
        {
            await connection.OpenAsync();

            await using var command = connection.CreateCommand();
            // The name is generated by the caller from a GUID, never user input.
            command.CommandText = $"CREATE DATABASE [{databaseName}]";
            await command.ExecuteNonQueryAsync();
        }

        return new SqlConnectionStringBuilder(ConnectionString)
        {
            InitialCatalog = databaseName,
        }.ConnectionString;
    }
}

/// <summary>Fixed identity so audit stamping can be asserted on.</summary>
public sealed class TestCurrentUser : ICurrentUser
{
    public TestCurrentUser(string? subjectId, Guid? tenantId = null)
    {
        SubjectId = subjectId;
        TenantId = tenantId;
    }

    public string? SubjectId { get; }

    public Guid? TenantId { get; }
}

/// <summary>Records what was dispatched, and when relative to the commit.</summary>
public sealed class RecordingDomainEventDispatcher : IDomainEventDispatcher
{
    private readonly List<IDomainEvent> _dispatched = [];

    public IReadOnlyList<IDomainEvent> Dispatched => _dispatched;

    public int DispatchCallCount { get; private set; }

    public Task DispatchAsync(
        IReadOnlyCollection<IDomainEvent> domainEvents,
        CancellationToken cancellationToken = default)
    {
        DispatchCallCount++;
        _dispatched.AddRange(domainEvents);
        return Task.CompletedTask;
    }
}

[CollectionDefinition(Name)]
public sealed class SqlServerCollection : ICollectionFixture<SqlServerFixture>
{
    public const string Name = "SqlServer";
}
